-- PyroSync: detecciones satelitales NRT separadas de la serie histórica armonizada.
-- Ejecutar en Supabase SQL Editor una sola vez.
CREATE TABLE IF NOT EXISTS public.live_hotspots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  detection_key TEXT NOT NULL UNIQUE,
  provider TEXT NOT NULL DEFAULT 'NASA FIRMS',
  product TEXT NOT NULL,
  satellite TEXT,
  instrument TEXT,
  acq_date DATE NOT NULL,
  acq_time TEXT NOT NULL,
  latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  brightness DOUBLE PRECISION,
  brightness_ti5 DOUBLE PRECISION,
  frp_mw DOUBLE PRECISION,
  confidence TEXT,
  scan_km DOUBLE PRECISION,
  track_km DOUBLE PRECISION,
  daynight TEXT,
  version TEXT,
  source_url TEXT,
  ingested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT live_hotspots_product_key UNIQUE (detection_key)
);

CREATE INDEX IF NOT EXISTS live_hotspots_acq_date_idx ON public.live_hotspots (acq_date DESC);
CREATE INDEX IF NOT EXISTS live_hotspots_ingested_at_idx ON public.live_hotspots (ingested_at DESC);
CREATE INDEX IF NOT EXISTS live_hotspots_lat_lon_idx ON public.live_hotspots (latitude, longitude);

CREATE TABLE IF NOT EXISTS public.firms_ingestion_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  status TEXT NOT NULL CHECK (status IN ('running','success','partial','failed')),
  sources TEXT[] NOT NULL DEFAULT '{}',
  bbox TEXT,
  day_range INTEGER,
  records_by_source JSONB NOT NULL DEFAULT '{}'::jsonb,
  raw_files JSONB NOT NULL DEFAULT '{}'::jsonb,
  errors JSONB NOT NULL DEFAULT '[]'::jsonb
);
CREATE INDEX IF NOT EXISTS firms_ingestion_runs_started_idx ON public.firms_ingestion_runs (started_at DESC);

ALTER TABLE public.live_hotspots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.firms_ingestion_runs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read live detections" ON public.live_hotspots;
CREATE POLICY "Public can read live detections" ON public.live_hotspots
  FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Public can read ingestion status" ON public.firms_ingestion_runs;
CREATE POLICY "Public can read ingestion status" ON public.firms_ingestion_runs
  FOR SELECT TO anon, authenticated USING (true);

-- La service_role del proceso de ingesta escribe; no se concede INSERT al cliente público.
GRANT SELECT ON public.live_hotspots, public.firms_ingestion_runs TO anon, authenticated;
GRANT ALL ON public.live_hotspots, public.firms_ingestion_runs TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

-- Activar Supabase Realtime para la tabla de detecciones si aún no está publicada.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'live_hotspots'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.live_hotspots;
  END IF;
EXCEPTION WHEN undefined_object THEN
  RAISE NOTICE 'La publicación supabase_realtime no existe; habilitar Realtime desde el Dashboard.';
END $$;
